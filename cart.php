  <script>

document.addEventListener(
    "DOMContentLoaded",
    function () {

        const checkoutButton =
            document.getElementById(
                "proceedCheckout"
            );


        if (!checkoutButton) {
            return;
        }


        checkoutButton.addEventListener(
            "click",
            function () {

                /* --------------------------------------
                   GET CART FROM LOCAL STORAGE
                -------------------------------------- */

                const storedCart =
                    localStorage.getItem("cart");


                console.log(
                    "Cart from localStorage:",
                    storedCart
                );


                if (!storedCart) {

                    alert(
                        "Your cart is empty."
                    );

                    return;

                }


                let cart;


                try {

                    cart =
                        JSON.parse(
                            storedCart
                        );

                } catch (error) {

                    console.error(
                        "Invalid cart JSON:",
                        error
                    );

                    alert(
                        "Your cart data is invalid."
                    );

                    return;

                }


                /* --------------------------------------
                   CHECK CART
                -------------------------------------- */

                if (
                    !Array.isArray(cart) ||
                    cart.length === 0
                ) {

                    alert(
                        "Your cart is empty."
                    );

                    return;

                }


                console.log(
                    "Products going to checkout:",
                    cart
                );


                /* --------------------------------------
                   CREATE POST FORM
                -------------------------------------- */

                const form =
                    document.createElement(
                        "form"
                    );


                form.method = "POST";

                form.action =
                    "checkout.php";


                /* --------------------------------------
